"""
Generated by Claude AI.

Generates a split-sum GGX BRDF LUT matching the engine's BRDF:
  - D_GGX (importance sampled, cancels out)
  - V_GGX (height-correlated Smith visibility)
  - Schlick Fresnel, split into A (scale on F0) and B (bias)

x = NoV, y = perceptual roughness (alpha = roughness^2)
Row 0 (top of the image) = roughness 0.

Outputs:
  brdf_lut.png  - 8-bit preview / usable LUT (R = A, G = B)
  brdf_lut.bin  - raw R16G16_FLOAT data, ready to upload as DXGI_FORMAT_R16G16_FLOAT

Requires: pip install numpy pillow
"""

import argparse
import numpy as np
from PIL import Image


def hammersley(n):
    i = np.arange(n, dtype=np.uint32)
    bits = i.copy()
    bits = ((bits << 16) | (bits >> 16)) & 0xFFFFFFFF
    bits = ((bits & 0x55555555) << 1) | ((bits & 0xAAAAAAAA) >> 1)
    bits = ((bits & 0x33333333) << 2) | ((bits & 0xCCCCCCCC) >> 2)
    bits = ((bits & 0x0F0F0F0F) << 4) | ((bits & 0xF0F0F0F0) >> 4)
    bits = ((bits & 0x00FF00FF) << 8) | ((bits & 0xFF00FF00) >> 8)
    return i / n, bits.astype(np.float64) * 2.3283064365386963e-10


def v_ggx(alpha, nov, nol):
    a2 = alpha * alpha
    ggxv = nol * np.sqrt(nov * nov * (1.0 - a2) + a2)
    ggxl = nov * np.sqrt(nol * nol * (1.0 - a2) + a2)
    ggx = ggxv + ggxl
    return np.where(ggx > 0.0, 0.5 / np.maximum(ggx, 1e-12), 0.0)


def integrate_row(nov, roughness, xi1, xi2):
    alpha = roughness * roughness

    # View vector, N = (0,0,1). Shape: (width, 1)
    vx = np.sqrt(1.0 - nov * nov)[:, None]
    vz = nov[:, None]

    # GGX importance-sampled half vectors. Shape: (1, samples)
    phi = 2.0 * np.pi * xi1
    cos_t = np.sqrt((1.0 - xi2) / (1.0 + (alpha * alpha - 1.0) * xi2))
    sin_t = np.sqrt(1.0 - cos_t * cos_t)
    hx = (sin_t * np.cos(phi))[None, :]
    hy = (sin_t * np.sin(phi))[None, :]
    hz = cos_t[None, :]

    # L = reflect(-V, H)
    voh = vx * hx + vz * hz
    lz = 2.0 * voh * hz - vz

    nol = np.clip(lz, 0.0, 1.0)
    noh = np.clip(hz, 0.0, 1.0)
    voh = np.clip(voh, 0.0, 1.0)

    valid = nol > 0.0
    vis = v_ggx(alpha, vz, nol) * 4.0 * voh * nol / np.maximum(noh, 1e-12)
    vis = np.where(valid, vis, 0.0)
    fc = (1.0 - voh) ** 5

    a = np.sum((1.0 - fc) * vis, axis=1) / xi1.size
    b = np.sum(fc * vis, axis=1) / xi1.size
    return a, b


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--size", type=int, default=256)
    parser.add_argument("--samples", type=int, default=1024)
    parser.add_argument("--flip", action="store_true", help="put roughness 0 at the bottom")
    args = parser.parse_args()

    size = args.size
    xi1, xi2 = hammersley(args.samples)
    nov = np.maximum((np.arange(size) + 0.5) / size, 1e-4)

    lut = np.zeros((size, size, 2), dtype=np.float64)
    for y in range(size):
        roughness = (y + 0.5) / size
        a, b = integrate_row(nov, roughness, xi1, xi2)
        lut[y, :, 0] = a
        lut[y, :, 1] = b

    if args.flip:
        lut = lut[::-1]

    # 8-bit PNG (R = A, G = B, B = 0)
    rgb = np.zeros((size, size, 3), dtype=np.uint8)
    rgb[..., :2] = np.clip(lut * 255.0 + 0.5, 0, 255).astype(np.uint8)
    Image.fromarray(rgb, "RGB").save("BRDFLUT.png")

    # Raw R16G16_FLOAT
    lut.astype(np.float16).tofile("BRDFLUT.bin")

    print(f"Wrote BRDFLUT.png and BRDFLUT.bin ({size}x{size}, {args.samples} samples)")


if __name__ == "__main__":
    main()
